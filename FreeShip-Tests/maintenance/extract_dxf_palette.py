"""Regenerate the exact Plus DXF palette; no installed files or baselines changed.

Run from any directory: python maintenance/extract_dxf_palette.py
The resulting header is versioned source, not a run-time Pascal dependency.
"""
import hashlib
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def main():
    source = ROOT / 'FreeShip-Plus-Lazarus/Units/FreeGeometry.pas'
    data = source.read_bytes()
    match = re.search(r'DXFLayerColors: array\[1\.\.255\] of TColor\s*=\s*\((.*?)\);', data.decode('utf-8-sig'), re.S)
    if not match:
        raise RuntimeError('Palette declaration changed')
    values = re.findall(r'\$([0-9a-fA-F]{6})', match[1])
    if len(values) != 255:
        raise RuntimeError('Expected the 255-entry Plus palette')
    rows = [', '.join('0x' + value.lower() for value in values[i:i+8]) for i in range(0, 255, 8)]
    text = ('// GPL-2.0-or-later. Exact DXFLayerColors from FreeGeometry.pas.\n'
            '// FREE!ship: Martijn van Engeland; Plus: Timoshenko and Malakanov.\n'
            '// Generated by FreeShip-Tests/maintenance/extract_dxf_palette.py.\n'
            '// Source SHA256: ' + hashlib.sha256(data).hexdigest() + '\n'
            '#pragma once\n#include <array>\nnamespace fs::document {\n'
            'inline constexpr std::array<int,255> DxfPalette = {\n    ' + ',\n    '.join(rows) + '\n};\n}\n')
    target = ROOT / 'FreeShip-Qt/src/document/dxf_palette.h'
    target.write_text(text, encoding='utf8', newline='\n')
    print(target)


if __name__ == '__main__':
    main()
