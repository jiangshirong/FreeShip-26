"""Extract protected Hydrodyn labels/help and retain reviewed numeric contracts.

No solver or formula is generated. Corrected bounds/units are explicit below;
the original LFM bounds clipped valid ship dimensions. --check is regression.
"""
import argparse, hashlib, json, re, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT/'FreeShip-Qt/bridge'))
from performance_adapter import lfm_nodes, field_map

METHODS = [('wind','Task1','空气动力特性','hydrodynamic_task1',11),
           ('maneuver','Maneuv','操纵性预估','maneuvering',19),
           ('acceleration','RVRS','加速与制动','reverse_propeller',16)]

def generate():
    hashes={}
    def read(name):
        data=(ROOT/'FreeShip-Plus-Lazarus'/name).read_bytes()
        hashes[name]=hashlib.sha256(data).hexdigest()
        return data.decode('utf-8-sig').replace('\r\n','\n')
    resources=read('Units/FreeResourceStrings.inc'); labels={};helptext={}
    for key,body in re.findall(r'(?m)^\s*(?:resourcestring\s+)?(rs_\w+)\s*=\s*((?:\'(?:\'\'|[^\'])*\'|#[0-9]+|\+|\s)+);',resources,re.I):
        value=''.join(chr(int(t[1:])) if t[0]=='#' else t[1:-1].replace("''", "'") for t in re.findall(r"'(?:''|[^'])*'|#\d+",body))
        helptext[key.lower()]=value
    # Reuse existing translations, do not create a new localization layer.
    for block in read('Locale/FreeShip.cn.po').split('\n\n'):
        a=re.search(r'^msgid (.*?)(?=^msgstr )',block,re.M|re.S);b=re.search(r'^msgstr (.*)',block,re.M|re.S)
        if not a or not b:continue
        decode=lambda s:''.join(json.loads(x) for x in re.findall(r'^".*"$',s,re.M))
        key,value=decode(a[1]),decode(b[1])
        if value:labels[key]=value
    defaults={
      'wind':[110,15,1000,400,250,160,55,4,5,10,45],
      'maneuver':[111,20,6,5,.6,2,49,10,1025,1.61,.25,50,2.5,.02,0,1,0,1,10],
      'acceleration':[110,15,5,5000,2000,1,4.685,.947,.55,4,.2,.15,3528,118,.9702,70,1]}
    bounds={
      'wind':[(0,1000),(0,100),(0,1e6),(0,1e6),(0,1e6),(0,1e5),(0,1000),(1,15),(0,100),(0,100),(-180,180)],
      'maneuver':[(0,1000),(0,200),(0,50),(0,50),(0,1),(-50,50),(0,100),(0,100),(1,2000),(0,100),(0,1),(1,1000),(0,100),(0,1),(-.15,.1),(0,2),(0,1),(0,2),(0,45)],
      'acceleration':[(0,1000),(0,200),(0,50),(0,1e9),(0,1e7),(1,3),(0,25),(0,1.5),(0,1.5),(2,8),(0,.99),(0,.99),(0,200000),(0,8000),(0,1),(0,5000),(1,3)]}
    integers={'wind':{9},'maneuver':{17,18,19},'acceleration':{7,11,18}}
    catalog={};bindings={}
    for method,entry,title,block,count in METHODS:
        lfm=read(f'Forms/FreeHydrodyn_{entry}Dlg.lfm');read(f'Forms/FreeHydrodyn_{entry}Dlg.pas')
        nodes=lfm_nodes(lfm);by={n['name']:n for n in nodes};fields=[];storage={}
        def caption(node):return node.get('Caption',"''")[1:-1].replace("''", "'")
        for name,label,unit,group in field_map(nodes):
            n=by[name];old=caption(by.get(label,n));text=labels.get(old,old)
            f=dict(key=name,label=text,unit='',group='计算选项' if n['class']=='TCheckBox' else '输入参数',visible=True,enabled=True)
            if n['class']=='TCheckBox':f.update(kind='boolean',value=False);storage[name]=dict(kind='boolean',offset=-1)
            else:
                i=int(name[4:]);lo,hi=bounds[method][i-2];integer=i in integers[method]
                f.update(kind='number',minimum=lo,maximum=hi,decimals=0 if integer else 6,value=defaults[method][i-2])
                storage[name]=dict(kind='number',minimum=lo,maximum=hi,integer=integer,offset=(i-2)*4 if block and i-2<count else -1,add=0)
            if method=='wind' and name=='Edit9':f['label']='桅杆组数／船型编号（1–15，见适用范围）'
            if method=='maneuver' and name=='Edit11':f['label']='运动黏度（10⁻⁶ m²/s）'
            if method=='maneuver' and name=='Edit18':f['label']='单桨艉型（0：封闭；1：敞开）'
            if method=='acceleration' and name=='Edit5':f['label']='排水体积 (m³)'
            if method=='acceleration' and name=='Edit17':f['label']='主机惯性矩（旧求解器输入值，见报告说明）'
            fields.append(f)
        note=helptext['rs_hydrodin_'+entry.lower()+'_note']
        catalog[method]=dict(calculator=method,title=title,fields=fields,help=labels.get(note,note),persistable=bool(block))
        if block:bindings[method]=dict(block=block,version=24 if method=='acceleration' else 38,fields=storage,extract_offset=count*4)
    read('Units/FreeTypes.pas');read('Units/FreeEdit.inc')
    return catalog,bindings,hashes

def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');a=p.parse_args()
    catalog,bindings,hashes=generate()
    data={'schema':catalog,'bindings':bindings}
    text='// GPL-2.0-or-later. Generated by maintenance/generate_hydrodynamics_tables.py.\nstatic constexpr auto HydrodynamicsTables = R"hydro('+json.dumps(data,ensure_ascii=False,separators=(',',':'))+')hydro";\n'
    for name,value in [('hydrodynamics_tables.h',text),('hydrodynamics-origin.json',json.dumps(hashes,indent=2,sort_keys=True)+'\n')]:
        path=ROOT/'FreeShip-Qt/src/document'/name
        if a.check:assert path.read_text('utf8')==value,name+' changed'
        else:path.write_text(value,encoding='utf8')
    print('Hydrodynamics source metadata: pass')
if __name__=='__main__':main()
