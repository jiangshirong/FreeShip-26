"""Auditable one-time arithmetic/report port for CALCPROP tasks 1-3.

Reads the protected Plus source. Produces ordinary C++ for review; it is not a
runtime interpreter. Process, files, inputs and validation are handwritten in
propulsion.cpp. --check verifies the retained generated fragments. Unsupported
Pascal syntax fails generation instead of being silently omitted.
"""
import argparse,json,re
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]

def clean(s):
    return re.sub(r"'(?:''|[^'])*'|\{.*?\}|\(\*.*?\*\)|//[^\n]*",lambda m:m[0] if m[0].startswith("'") else '',s,flags=re.S)

class Port:
    def __init__(self,s):
        self.t=re.findall(r"'(?:''|[^'])*'|[A-Za-z_]\w*|\d+(?:\.\d*)?(?:[Ee][+-]?\d+)?|:=|<>|<=|>=|[^\s]",s);self.p=0
    def peek(self):return self.t[self.p].lower() if self.p<len(self.t) else ''
    def pop(self):
        t=self.t[self.p];self.p+=1;return t
    def want(self,t):assert self.pop().lower()==t,(t,self.t[self.p-8:self.p+8])
    def expr(self,ends):
        out=[];depth=0
        while self.p<len(self.t):
            t=self.peek()
            if depth==0 and t in ends:break
            tok=self.pop()
            if tok=='[':
                parts=[]
                while True:
                    parts.append(self.expr({',',']'}))
                    if self.pop()==']':break
                out.append(''.join('['+v+']' for v in parts));continue
            if tok=='(':depth+=1
            if tok==')':depth-=1
            if tok.startswith("'"):tok='QStringLiteral('+json.dumps(tok[1:-1].replace("''","'"),ensure_ascii=False)+')'
            elif t.startswith('rs_'):tok='r("'+t+'")'
            elif re.fullmatch(r'dat\d+(?:_\d+)?',t):tok='d("Edit'+t[3:]+'")'
            elif t=='resultsMemo'.lower():tok='resultsmemo'
            else:tok={'and':'&&','or':'||','not':'!','=':'==','<>':'!=','power':'std::pow','arctan':'std::atan','sin':'std::sin','cos':'std::cos','tan':'std::tan','ffFixed'.lower():'0','floatToStrF'.lower():'format','space':'space','makelength':'pad','sfinex1':'interpolate'}.get(t,t if re.match(r'^[A-Za-z_]',tok) else tok)
            out.append(tok)
        return ' '.join(out)
    def statement(self,indent=1):
        prefix='    '*indent;t=self.peek()
        if t==';':self.pop();return ''
        if t=='begin':
            self.pop();out=prefix+'{\n'
            while self.peek()!='end':out+=self.statement(indent+1)
            self.pop();return out+prefix+'}\n'
        if t=='if':
            self.pop();condition=self.expr({'then'});self.want('then');out=prefix+'if ('+condition+')\n'+self.statement(indent+1)
            if self.peek()=='else':self.pop();out+=prefix+'else\n'+self.statement(indent+1)
            return out
        if t=='for':
            self.pop();var=self.pop().lower();self.want(':=');start=self.expr({'to','downto'});down=self.pop().lower()=='downto';end=self.expr({'do'});self.want('do')
            return prefix+f'for ({var}={start}; {var}{">=" if down else "<="}{end}; {"--" if down else "++"}{var})\n'+self.statement(indent+1)
        expr=self.expr({';','end','else'})
        if self.peek()==';':self.pop()
        if expr=='exit':expr='return'
        elif ':=' in expr:
            left,right=expr.split(':=',1);left=left.strip();right=right.strip()
            if left.startswith('d('):expr='set('+left[2:-1]+', '+right+')'
            elif left=='chart . leftaxis . title . caption':expr='axisY = '+right
            elif '. visible' in left or left=='validdata':return ''
            else:expr=left+' = '+right
        elif expr.startswith('resultsmemo . lines . add ('):expr='line('+expr[len('resultsmemo . lines . add ('):-1]+')'
        elif m:=re.match(r'(series\w+) \. addxy \((.*)\)',expr):
            args=split_args(m[2]);expr='point("'+m[1]+'", '+args[0]+', '+args[1]+')'
        elif expr.startswith('messagedlg ('):
            expr='bad('+split_args(expr[len('messagedlg ('):-1])[0]+')'
        return prefix+expr+';\n'
    def run(self):
        out=''
        while self.p<len(self.t):out+=self.statement()
        return out

def split_args(s):
    result=[];start=0;depth=0
    for i,c in enumerate(s):
        if c in '([':depth+=1
        elif c in ')]':depth-=1
        elif c==',' and depth==0:result.append(s[start:i].strip());start=i+1
    return result+[s[start:].strip()]

def generate():
    out='// GPL-2.0-or-later. Plus CALCPROP postprocessing, Timoshenko V.F.\n// Generated by maintenance/port_propulsion_reports.py; process/file handling is separate.\n'
    for n in (1,2,3):
        text=(ROOT/f'FreeShip-Plus-Lazarus/Forms/FreePropeller_Task{n}Dlg.pas').read_text('utf-8-sig')
        body=clean(text.split(f'procedure TFreePropeller_Task{n}.CalculateInWorkspace;',1)[1].split(f'end;{{TFreePropeller_Task{n}.Calculate}}',1)[0])
        variables=body.split('var',1)[1].split('label',1)[0]
        decl=[]
        for names,kind in re.findall(r'([\w,\s]+):\s*(integer|single|string|array[^;]+);',variables,re.I):
            names=[v.strip().lower() for v in names.strip().split(',')]
            names=[v for v in names if v not in ('res','z','ae_ao','strp','processcallerdirectory','pathfileold','filename','fexecdirectory','fopendirectory','execfullname','patHfile'.lower(),'filetofind')]
            if not names:continue
            if kind.lower().startswith('array'):
                dims=re.findall(r'\d+\.\.(\d+)',kind);typ='QString' if 'string' in kind else 'float'
                decl.extend(typ+' '+name+''.join('['+str(int(d)+1)+']' for d in dims)+'{};' for name in names)
            else:decl.extend({'integer':'int','single':'float','string':'QString'}[kind.lower()]+' '+name+'{};' for name in names)
        if n in (1,2):body=body[body.index('ValidData := True;'):body.rindex('finally')]
        else:
            body=body[body.index('  ResultsMemo.Visible := True;',body.index("FileName := 'RES3.tsk';",body.index('ExecuteFreeCalculation'))):body.rindex('finally')]
        if n==1:
            # Original loop read hp[5]/Teta[5] beyond their four-element arrays.
            body=body.replace('for i := 1 to 4 do','for i := 1 to 3 do')
        if n==2:
            start=body.index('  Assignfile(');end=body.index('  CloseFile(FFile);',start)+len('  CloseFile(FFile);')
            body=body[:start]+'publish_propeller(Dp,P_D,Ae_Ao,Z,Jp,Kt,Kq,ETAo);'+body[end:]
            # The original printed a universal conclusion using only material 8
            # and tested SigmaB>.25 for a line labeled SigmaB/4>1. Keep the
            # computed eight columns; evaluate each stated criterion literally.
            start=body.index('  if SigmaB > 1 then');end=body.index("  ResultsMemo.Lines.Add('');",start)
            verdict="""if SigmaB > 1 then
ResultsMemo.Lines.Add(Space(10) + 'SigmaB > 1: ' + rs_Propeller_is_a_strong_in_uniform_flow_)
else
ResultsMemo.Lines.Add(Space(10) + 'SigmaB <= 1: ' + rs_This_is_propeller_not_a_strong_in_uniform_flow_);
if SigmaB > 4 then
ResultsMemo.Lines.Add(Space(10) + 'SigmaB/4 > 1: ' + rs_Propeller_is_a_strong_in_non_uniform_flow_)
else
ResultsMemo.Lines.Add(Space(10) + 'SigmaB/4 <= 1: ' + rs_This_is_propeller_not_a_strong_in_non_uniform_flow_);
"""
            body=body[:start]+"for i := 1 to 8 do begin\nSigmaB := Res1[i,7];\nResultsMemo.Lines.Add('材料 ' + FloatToStrF(i,ffFixed,6,0));\n"+verdict+'end;\n'+body[end:]
            decl+=['const float rom[9]={0,8.4f,8.8f,7.8f,8.5f,7.7f,7.7f,7.9f,2.8f};','const float sigmat[9]={0,195,215,224,242,272,292,438,430};']
        if n==3:
            start=body.index('  if FileExistsUTF8(');end=body.index('  CloseFile(FFile);',start)+len('  CloseFile(FFile);')
            body=body[:start]+'resistance_curves(km,kt);'+body[end:]
            decl.append('psp=d("Edit17");')
        code=Port(body).run()
        decl=[v for v in decl if not re.match(r'(?:int|float|QString) (\w+)(?:\[|\{)',v) or re.search(r'\b'+re.match(r'(?:int|float|QString) (\w+)',v)[1]+r'\b',code)]
        out+=f'void Calculation::legacy{n}([[maybe_unused]] float z,[[maybe_unused]] float ae_ao,[[maybe_unused]] const QString& strp) {{\n'
        out+='\n'.join('    '+v for v in decl)+'\n'+code+'}\n'
    return out

def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');a=p.parse_args();s=generate();path=ROOT/'FreeShip-Qt/src/document/propulsion_reports.inc'
    if a.check:assert path.read_text('utf8')==s,'review/regenerate propulsion reports'
    else:path.write_text(s,encoding='utf8')
    print('propulsion report port: pass')
if __name__=='__main__':main()
