"""Rebuild/check native calculator field metadata from the protected Plus source.

Only declarations, serialized record order and direct input bindings are read.
No formula is auto-translated. Side-effecting getters are intentionally replaced
by explicit input storage; estimated wetted area is handled in analysis_edit.cpp.
Run --check in qt-document. Regeneration is a reviewed maintenance operation.
"""
import argparse,hashlib,json,re,sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
sys.path.insert(0,str(ROOT/'FreeShip-Qt/bridge'))
from performance_adapter import METHODS,lfm_nodes,field_map
BLOCKS=[('delft',16),('holtr',22),('hollenbach',25),('oortmerssen',33),('fung',35),
        ('ost',22),('rbhs',40),('mh',40),('kaper',16),('planing',23),
        ('propeller_task1',22),('propeller_task2',22),('propeller_task3',22),('propeller_task4',26),('propeller_task5',30)]

def generate():
    source=ROOT/'FreeShip-Plus-Lazarus';hashes={}
    def read(name):
        data=(source/name).read_bytes();hashes[name]=hashlib.sha256(data).hexdigest();return data.decode('utf-8-sig')
    edit=read('Units/FreeEdit.inc');types=read('Units/FreeTypes.pas');ship=read('Units/FreeShipUnit.pas');result={}
    for (method,entry,_),(block,version) in zip(METHODS,BLOCKS):
        text=read(f'Forms/Free{entry}Dlg.pas');lfm=read(f'Forms/Free{entry}Dlg.lfm');cls='TFree'+entry
        nodes=lfm_nodes(lfm);fields={n['name']:n for n in nodes};names={k.lower():k for k in fields}
        body=re.search(r'procedure TFreeEdit\.'+entry+r';(.*?)end;\{TFreeEdit\.'+entry+r'\}',edit,re.S|re.I)[1]
        store=body[body.index('  if Dialog.Execute'):body.index('  FreeAndNil(Dialog);')]
        record=re.search(r'FreeShip\.(F\w+Data)\.',store)[1]
        typename=re.search(r'\b'+record+r':\s*(\w+);',ship,re.I)[1]
        record_body=re.search(r'\b'+typename+r'\s*=\s*record(.*?)\bend;',types,re.S|re.I)[1]
        offsets={};at=0
        for name,kind in re.findall(r'(\w+)\s*:\s*(TFloatType|boolean)\s*;',record_body,re.I):
            offsets[name.lower()]=at;at+=1 if kind.lower()=='boolean' else 4
        mappings={}
        for target,prop in re.findall(r'FreeShip\.(\w+\.\w+)\s*:=\s*Dialog\.([\w.]+);',store,re.I):
            if prop.lower()=='checkbox2.checked':continue
            getter=re.search(r'property\s+'+prop+r':\s*\w+\s+read\s+(\w+)',text,re.I)[1]
            g=re.search(r'function '+cls+r'\.'+getter+r'\b.*?\bbegin\b(.*?)end;\{'+cls+r'\.'+getter+r'\}',text,re.S|re.I)[1]
            # The first assignment is the actual getter return. Some old getters
            # subsequently modify controls; those UI side effects are not data.
            matches=re.findall(r'Result\s*:=\s*(\w+)\.(Value|Checked|ItemIndex)(\s*\+\s*1)?\s*;',g,re.I)
            assert matches,(method,prop)
            control,kind,add=matches[0];control=names[control.lower()]
            if control.lower()=='checkbox2':continue
            target_record,member=target.split('.')
            mappings[control]=dict(offset=-2 if target_record=='ProjectSettings' else offsets[member.lower()],add=1 if add else 0,member=member)
        schema={}
        for name,_,_,_ in field_map(nodes):
            n=fields[name];kind=n['class'];row=dict(mappings.get(name,dict(offset=-1,add=0)))
            if kind=='TCheckBox':row['kind']='boolean'
            elif kind in ('TComboBox','TRadioGroup'):
                # LFM item strings are not flattened by lfm_nodes.
                match=re.search(r'(?m)^(\s*)object '+name+r':.*?\n\1end\s*$',lfm,re.S)
                items=re.search(r'Items.Strings = \((.*?)\)',match[0],re.S)
                row.update(kind='choice',count=len(re.findall(r"(?m)^\s*'",items[1])) if items else 0)
                if name=='ComboBox' and method in ('rbhs','mh'):row['count']=9
            else:
                lo=float(n.get('MinValue','0'));hi=float(n.get('MaxValue','0'))
                if kind=='TFloatSpinEdit' and hi<=lo:lo,hi=-1e9,1e9
                if method=='hollenbach' and name=='StepSpeedBox':hi=1050
                if method=='mh' and name=='NserBox':hi=24
                row.update(kind='number',minimum=lo,maximum=hi,integer=kind=='TSpinEdit')
            schema[name]=row
        result[method]=dict(block=block,version=version,fields=schema,extract_offset=offsets['extract'])
    data=json.dumps(result,ensure_ascii=True,separators=(',',':'),sort_keys=True)
    return '// GPL-2.0-or-later. Generated by FreeShip-Tests/maintenance/generate_analysis_fields.py.\n'+\
        '// Plus declarations and input bindings; see analysis_edit.cpp for behavior.\n'+\
        'static constexpr auto AnalysisFields = R"fields('+data+')fields";\n',hashes

def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');a=p.parse_args()
    data,hashes=generate();target=ROOT/'FreeShip-Qt/src/document/analysis_fields.h'
    provenance=ROOT/'FreeShip-Qt/src/document/analysis-fields-origin.json';origin=json.dumps(hashes,indent=2,sort_keys=True)+'\n'
    if a.check:
        assert target.read_text('utf8')==data,'Regenerate/review calculator fields'
        assert provenance.read_text('utf8')==origin,'Calculator source changed'
    else:target.write_text(data,encoding='utf8');provenance.write_text(origin,encoding='utf8')
    print(json.dumps(dict(status='pass',methods=len(METHODS),sources=len(hashes))))
if __name__=='__main__':main()
