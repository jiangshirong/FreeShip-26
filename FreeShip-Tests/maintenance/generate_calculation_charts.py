"""Retain declared chart line styles from original LFM forms, without formulas."""
import argparse,hashlib,json,re,sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
sys.path.insert(0,str(ROOT/'FreeShip-Qt/bridge'))
from performance_adapter import METHODS
COLORS=dict(clBlack='#000000',clBlue='#0000ff',clGreen='#008000',clRed='#ff0000',
            clNavy='#000080',clFuchsia='#ff00ff',clMaroon='#800000',clTeal='#008080',
            clGray='#808080',clLime='#00ff00',clPurple='#800080',clAqua='#00ffff',clYellow='#ffff00')
def generate():
    data={};hashes={}
    for method,entry,_ in METHODS+[(m,'Hydrodyn_'+f,'') for m,f in [('wind','Task1'),('acceleration','RVRS')]]:
        name='Forms/Free'+entry+'Dlg.lfm';raw=(ROOT/'FreeShip-Plus-Lazarus'/name).read_bytes();hashes[name]=hashlib.sha256(raw).hexdigest();source=raw.decode('utf-8-sig')
        rows=[]
        for match in re.finditer(r'(?ms)^( *)object (\w+): TLineSeries\s*\n(.*?)^\1end',source):
            props=dict(re.findall(r'(?m)^ {%d}([\w.]+) = (.*)$'%(len(match[1])+2),match[3]));color=props.get('LinePen.Color','clBlack').strip()
            if color in COLORS:rgb=COLORS[color]
            else:
                numeric=int(color[1:],16) if color.startswith('$') else int(color)
                if not 0<=numeric<=0xffffff:raise ValueError((method,color))
                rgb='#%02x%02x%02x'%(numeric&255,(numeric>>8)&255,(numeric>>16)&255)
            rows.append(dict(source=match[2],color=rgb,width=int(props.get('LinePen.Width',1)),
                style=props.get('LinePen.Style','psSolid').strip(),points=props.get('ShowPoints','False').strip()=='True'))
        if not rows:raise ValueError('No curves: '+method)
        data[method]=dict(series=rows,legend_right='Legend.Alignment = laCenterRight' in source)
    return data,hashes
def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');a=p.parse_args();data,hashes=generate()
    header='// SPDX-License-Identifier: GPL-2.0-or-later\n// Generated by generate_calculation_charts.py from preserved LFM forms.\nstatic constexpr auto CalculationChartStyles=R"charts('+json.dumps(data,separators=(',',':'))+')charts";\n'
    for name,value in [('calculation_charts.h',header),('calculation_charts-origin.json',json.dumps(hashes,sort_keys=True,indent=2)+'\n')]:
        path=ROOT/'FreeShip-Qt/src/app'/name
        if a.check:assert path.read_text('utf8')==value,name
        else:path.write_text(value,encoding='utf8')
    print('Chart style provenance: pass')
if __name__=='__main__':main()
