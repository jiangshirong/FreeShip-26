"""Retain the Qt propulsion field contract and Plus report translations.

--capture-catalog reads an explicitly selected, retained legacy service catalog.
Normal regeneration reads only the frozen contract and protected source. No
calculation formula or solver result is generated by this script.
"""
import argparse, hashlib, json, re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'FreeShip-Plus-Lazarus'
DEST = ROOT / 'FreeShip-Qt/src/document'
CONTRACT = ROOT / 'FreeShip-Tests/fixtures/propulsion/schema.json'

def generate():
    hashes = {}
    def read(name):
        b=(SOURCE/name).read_bytes();hashes[name]=hashlib.sha256(b).hexdigest();return b.decode('utf-8-sig').replace('\r\n','\n')
    po=read('Locale/FreeShip.cn.po');strings={}
    for block in po.split('\n\n'):
        refs=re.findall(r'^#: (.*)',block,re.M);m=re.search(r'^msgstr (.*)',block,re.M)
        if not m:continue
        value=''.join(json.loads(x) for x in re.findall(r'^".*"$',block[m.start()+7:],re.M))
        if value:
            for ref in ' '.join(refs).split():strings[ref.split('.')[-1].lower()]=value
    # Resource fallback for untranslated strings, preserving explicit line breaks.
    resources=read('Units/FreeResourceStrings.inc')
    for key,body in re.findall(r'(?m)^\s*(?:resourcestring\s+)?(rs_\w+)\s*=\s*((?:\'(?:\'\'|[^\'])*\'|#[0-9]+|\+|\s)+);',resources,re.I):
        words=re.findall(r"'(?:''|[^'])*'|#\d+",body)
        value=''.join(chr(int(t[1:])) if t[0]=='#' else t[1:-1].replace("''", "'") for t in words)
        strings.setdefault(key.lower(),value)
    indexed={int(n):key.lower() for n,key in re.findall(r'UserStrings\[\s*(\d+)\]\s*:=\s*(\w+);',read('Units/FreeUserStringsArray.inc'))}
    used=set();series={};setters={}
    for n in range(1,6):
        s=read(f'Forms/FreePropeller_Task{n}Dlg.pas');lfm=read(f'Forms/FreePropeller_Task{n}Dlg.lfm')
        used.update(k.lower() for k in re.findall(r'\brs_\w+',s))
        series[str(n)]=[]
        # Field order is the chart's published component order, not name sorting.
        for name,body in re.findall(r'object (Series\w+): TLineSeries(.*?)(?=\n\s*end)',lfm,re.S):
            title=re.search(r"Title = '((?:''|[^'])*)'",body)
            series[str(n)].append(dict(source=name,name=title[1].replace("''", "'") if title else ''))
        setters[str(n)]={}
        for key,body in re.findall(r'procedure TFreePropeller_Task\d\.FSet(Dat\w+)\(val: single\);(.*?)end;\{TFreePropeller_Task\d\.FSet',s,re.S):
            setters[str(n)][key]=body
    # Numbered labels used in report loops; these were blank in the old bridge
    # because SetUserStringsLang was never called. Preserve their intended labels.
    indices=list(range(350,510))+list(range(740,770))+list(range(849,880))+list(range(900,996))
    numbered={str(i):strings.get(indexed.get(i,''),'') for i in indices}
    data=dict(schema=json.loads(CONTRACT.read_text('utf8')),strings={k:strings.get(k,'') for k in sorted(used)},numbered=numbered,series=series)
    assert all(data['strings'][k] for k in used if k!='rs_'),[k for k in used if not data['strings'][k]]
    hashes['Qt field contract']=hashlib.sha256(CONTRACT.read_bytes()).hexdigest()
    return '// GPL-2.0-or-later. Generated by maintenance/generate_propulsion_tables.py.\n'+\
        'static constexpr auto PropulsionTables = R"prop('+json.dumps(data,ensure_ascii=False,separators=(',',':'))+')prop";\n',hashes

def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');p.add_argument('--capture-catalog',type=Path);a=p.parse_args()
    if a.capture_catalog:
        catalog=json.loads(a.capture_catalog.read_text('utf8'));data={}
        for n in range(1,6):
            method=f'propeller{n}';s=catalog[method];data[method]={k:s[k] for k in ('fields','title','calculator')}
        CONTRACT.parent.mkdir(parents=True,exist_ok=True);CONTRACT.write_text(json.dumps(data,ensure_ascii=False,indent=2)+'\n',encoding='utf8')
    text,origin=generate();origin=json.dumps(origin,sort_keys=True,indent=2)+'\n'
    for name,value in [('propulsion_tables.h',text),('propulsion-origin.json',origin)]:
        path=DEST/name
        if a.check:assert path.read_text('utf8')==value,name+' is stale'
        else:path.write_text(value,encoding='utf8')
    print('propulsion field/translation provenance: pass')
if __name__=='__main__':main()
